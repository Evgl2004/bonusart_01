"""
Служебные представления для новой пользовательской навигации.

Назначение:
1. Дать стабильные URL для новых разделов интерфейса.
2. Не ломать существующие (legacy) страницы, которые остаются доступными по прямым ссылкам.
3. Позволить внедрять UI поэтапно: сначала структура меню, затем бизнес-функционал.
"""

from __future__ import annotations

from django.views.generic import TemplateView


class _SectionStubView(TemplateView):
    """
    Базовая заглушка раздела интерфейса.

    Используется как временный контейнер, пока в разделе идет
    поэтапная реализация бизнес-логики и экранов.
    """

    template_name = "placeholders/section_stub.html"
    page_title = "Раздел в разработке"
    page_description = "Раздел подключен в навигацию и будет заполнен на следующем этапе."
    page_next_steps: list[str] = []

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)
        context["page_title"] = self.page_title
        context["page_description"] = self.page_description
        context["page_next_steps"] = self.page_next_steps
        return context


